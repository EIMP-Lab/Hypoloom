"""Narrow typed ports around the Hypoloom core."""
from __future__ import annotations
from contextlib import AbstractContextManager
from datetime import datetime
from typing import Any, Mapping, Protocol, Sequence, TypeAlias, TypeVar
from .domain import AttemptId, CommandId, ExecutionId, FactId, ResearchFactType, RunId, WorkflowId
Row = Mapping[str, Any]
class Clock(Protocol):
    def now(self) -> datetime: ...
class IdSource(Protocol):
    def new_id(self, namespace: str) -> str: ...
class WorkflowStore(Protocol):
    def latest_transition(self, workflow_id: WorkflowId) -> Row | None: ...
    def get_run(self, run_id: RunId) -> Row | None: ...
    def append_transition(self, mutation: Row) -> bool: ...
class ResearchStore(Protocol):
    def get_attempt(self, attempt_id: AttemptId) -> Row | None: ...
    def list_attempts(self, *, workflow_id: str | None = None) -> Sequence[Row]: ...
    def get_fact(self, fact_id: FactId) -> Row | None: ...
    def find_fact(
        self, run_id: RunId, fact_type: ResearchFactType, subject_id: str | None = None
    ) -> Row | None: ...
    def list_facts(
        self, run_id: RunId, fact_type: ResearchFactType | None = None
    ) -> Sequence[Row]: ...
    def append_fact(self, mutation: Row) -> bool: ...
class ExecutionStore(Protocol):
    def get_attempt(self, attempt_id: AttemptId) -> Row | None: ...
    def list_attempts(
        self,
        *,
        workflow_id: WorkflowId | None = None,
        command_id: CommandId | None = None,
        execution_id: ExecutionId | None = None,
    ) -> Sequence[Row]: ...
    def open_attempt(self, mutation: Row) -> bool: ...
    def close_attempt(self, attempt_id: AttemptId, observation: Row) -> bool: ...
    def record_artifact(self, mutation: Row) -> bool: ...
class StateTransaction(WorkflowStore, ResearchStore, ExecutionStore, Protocol):
    pass
class StateStore(Protocol):
    def transaction(self) -> AbstractContextManager[StateTransaction]: ...
RequestT = TypeVar("RequestT", contravariant=True)
ResponseT = TypeVar("ResponseT", covariant=True)
class EffectPort(Protocol[RequestT, ResponseT]):
    def invoke(self, request: RequestT) -> ResponseT: ...
AgentEffect: TypeAlias = EffectPort[RequestT, ResponseT]
ProcessEffect: TypeAlias = EffectPort[RequestT, ResponseT]
